function checkpointJson = serializeExactWeaveCursorJson( ...
        originalLengths, cursor)
% Natywny tekstowy checkpoint eksperymentalnego rank/unrank (v1).
% Jest to JSON, ale wielkie liczby sa zapisane TYLKO jako dziesietne
% lancuchy znakow. MATLAB jsonencode nigdy nie otrzymuje BigInt
% do niebezpiecznej konwersji na float.
%
% Export waliduje ksztalt, skladnie i zakresy podstawowe. Pelna
% walidacja dokladnej liczby kontynuacji nastepuje podczas IMPORTU,
% ktory uruchamia niezaleznie sprawdzony zerokrokowy licznik.
% Brak podpisu lub gwarancji odpornosci na zlosliwa podmiane pliku.

if ~(isnumeric(originalLengths) && isvector(originalLengths) && ...
        ~isempty(originalLengths) && isreal(originalLengths) && ...
        all(isfinite(originalLengths)) && ...
        all(originalLengths>0) && ...
        all(fix(originalLengths)==originalLengths) && ...
        all(originalLengths<=flintmax))
    error('Pastafari:WeaveCheckpoint:Lengths', ...
        'Original month lengths must be positive exact integers.');
end
L=double(originalLengths(:).');
K=numel(L);
required={'remaining','openedUpTo','closedUpTo','rank','count','done', ...
    'stepsComputed'};
if ~(isstruct(cursor) && isscalar(cursor) && ...
        all(isfield(cursor,required)))
    error('Pastafari:WeaveCheckpoint:Cursor', ...
        'Cursor does not contain all required scalar fields.');
end
R=cursor.remaining;
if ~(isnumeric(R) && isvector(R) && isreal(R) && ...
        numel(R)==K && all(isfinite(R)) && ...
        all(fix(R)==R) && all(R>=0) && all(R<=L))
    error('Pastafari:WeaveCheckpoint:Remaining', ...
        'Remaining month multiplicities must match original lengths.');
end
R=double(R(:).');
o=cursor.openedUpTo;
c=cursor.closedUpTo;
if ~(isnumeric(o) && isscalar(o) && isreal(o) && ...
        isfinite(o) && fix(o)==o && ...
        isnumeric(c) && isscalar(c) && isreal(c) && ...
        isfinite(c) && fix(c)==c && ...
        0<=c && c<=o && o<=K) || ...
        any(R(1:c)~=0) || ...
        any(R(c+1:o)<=0) || any(R(c+1:o)>=L(c+1:o)) || ...
        any(R(o+1:end)~=L(o+1:end))
    error('Pastafari:WeaveCheckpoint:Frontier', ...
        'Opening/closure indices contradict the remaining multiplicities.');
end
if ~(islogical(cursor.done) && isscalar(cursor.done) && ...
        cursor.done==all(R==0))
    error('Pastafari:WeaveCheckpoint:Done', ...
        'Completion flag must match exact remaining multiplicities.');
end
steps=cursor.stepsComputed;
if ~(isnumeric(steps) && isscalar(steps) && ...
        isreal(steps) && isfinite(steps) && ...
        fix(steps)==steps && steps>=0 && steps<=flintmax)
    error('Pastafari:WeaveCheckpoint:Steps', ...
        'Steps computed must be a nonnegative exact integer.');
end
pastafari.ValidationManager.requireExactIntegerInput(cursor.rank);
pastafari.ValidationManager.requireExactIntegerInput(cursor.count);
rank=pastafari.BigInt.coerce(cursor.rank);
count=pastafari.BigInt.coerce(cursor.count);
one=pastafari.BigInt(1);
if rank<one || count<one || rank>count || ...
        (cursor.done && (rank~=one || count~=one))
    error('Pastafari:WeaveCheckpoint:Rank', ...
        'Rank must be exact, positive and inside the count range.');
end
record=struct( ...
    'schema','pastafari-weave-cursor-v1', ...
    'originalLengths',L, ...
    'remaining',R, ...
    'openedUpTo',o, ...
    'closedUpTo',c, ...
    'rankDecimal',char(rank), ...
    'countDecimal',char(count), ...
    'done',cursor.done, ...
    'stepsComputed',steps);
checkpointJson=jsonencode(record);
end
