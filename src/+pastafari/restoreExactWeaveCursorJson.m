function [originalLengths, cursor] = restoreExactWeaveCursorJson( ...
        checkpointJson)
% Odtworzenie przenosnego checkpointu rank/unrank v1.
% Kazda liczba BigInt jest parsowana z kanonicznego tekstu dziesietnego.
% Cale pochodne count jest liczone od nowa, bez zaufania do pola JSON;
% w ten sposob uszkodzony lub podmieniony stan NIE moze byc uznany
% za dokladny punkt wznowienia. Brak podpisu/authenticated checkpoint.
if ~(ischar(checkpointJson) && isrow(checkpointJson) && ...
        ~isempty(checkpointJson)) && ...
        ~(isstring(checkpointJson) && isscalar(checkpointJson))
    error('Pastafari:WeaveCheckpoint:JSON', ...
        'Checkpoint must be a single JSON text value.');
end
try
    obj=jsondecode(char(checkpointJson));
catch
    error('Pastafari:WeaveCheckpoint:JSON', ...
        'Unable to parse checkpoint JSON.');
end
fields={'schema','originalLengths','remaining','openedUpTo', ...
    'closedUpTo','rankDecimal','countDecimal','done','stepsComputed'};
if ~(isstruct(obj) && isscalar(obj) && ...
        numel(fieldnames(obj))==numel(fields) && ...
        all(isfield(obj,fields)) && ...
        ischar(obj.schema) && ...
        strcmp(obj.schema,'pastafari-weave-cursor-v1'))
    error('Pastafari:WeaveCheckpoint:Schema', ...
        'Unknown or incomplete exact checkpoint schema.');
end
decimalFields={obj.rankDecimal,obj.countDecimal};
for i=1:2
    value=decimalFields{i};
    if ~(ischar(value) && isrow(value) && ...
            ~isempty(regexp(value,'^[1-9][0-9]*$','once')))
        error('Pastafari:WeaveCheckpoint:Decimal', ...
            'BigInt must be a canonical positive decimal string.');
    end
end
if ~(islogical(obj.done) && isscalar(obj.done))
    error('Pastafari:WeaveCheckpoint:Done', ...
        'Completion flag must be a true JSON boolean.');
end
pastafari.ValidationManager.requireExactIntegerInput( ...
    obj.openedUpTo);
pastafari.ValidationManager.requireExactIntegerInput( ...
    obj.closedUpTo);
pastafari.ValidationManager.requireExactIntegerInput( ...
    obj.stepsComputed);
saved=struct('remaining',obj.remaining, ...
    'openedUpTo',obj.openedUpTo, ...
    'closedUpTo',obj.closedUpTo, ...
    'rank',pastafari.BigInt(obj.rankDecimal), ...
    'count',pastafari.BigInt(obj.countDecimal), ...
    'done',obj.done, ...
    'stepsComputed',obj.stepsComputed);

% Validate primitive representation and frontier before any expensive
% BigInt DP computation. Import never uses persisted child count
% to skip the independent exact verification.
serializeExactWeaveCursorJson(obj.originalLengths,saved);

[none,recomputed]=pastafari.unrankGeneralWeaveSuffixChunkLazyJoint( ...
    obj.originalLengths,obj.remaining,obj.openedUpTo, ...
    obj.closedUpTo,saved.rank,0);
if ~isempty(none) || recomputed.count~=saved.count || ...
        recomputed.rank~=saved.rank || ...
        recomputed.done~=saved.done
    error('Pastafari:WeaveCheckpoint:CountMismatch', ...
        'The persisted BigInt count does not match verified suffix count.');
end
originalLengths=double(obj.originalLengths(:).');
cursor=saved;
cursor.initialCount=saved.count;
end
