#!/usr/bin/env python3
"""SQL+தமிழ் Slice23 independent rank oracle: brute enumeration and prefix subtraction.

No SQL production imports; expected tuples computed before PostgreSQL evaluation.
Use --self-test, --emit-sql, or --emit-hashes.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from itertools import permutations
from math import perm


def expected_indices(n: int, k: int, rank1: int) -> tuple[int, ...]:
    if not (1 <= k <= n and 1 <= rank1 <= perm(n, k)):
        raise ValueError("rank out of range")
    left = list(range(1, n+1))
    out: list[int] = []
    remaining_rank = rank1
    while len(out) < k:
        suffix_length = k-len(out)-1
        for candidate in left:
            prefix_count = perm(len(left)-1, suffix_length)
            if remaining_rank > prefix_count:
                remaining_rank -= prefix_count
            else:
                out.append(candidate)
                left.remove(candidate)
                break
        else:
            raise AssertionError("rank was not resolved")
    assert remaining_rank == 1
    return tuple(out)


def cases() -> list[tuple[str, int, int, tuple[int, ...]]]:
    cases_out = []
    for k in (3, 4, 5, 7, 12, 17, 31, 47):
        count = perm(47, k)
        ranks = (1, 2, 3, count//2, count//2+1, count-2, count-1, count)
        assert len(set(ranks)) == 8
        for n, rank in enumerate(ranks, 1):
            expected = expected_indices(47, k, rank)
            cases_out.append((f"k{k:02d}-r{n}", k, rank, expected))
    assert len(cases_out) == 64 and len({n for n,_,_,_ in cases_out}) == 64
    return cases_out


def self_test() -> None:
    total = 0
    for n in (3, 4, 5, 6):
        for k in range(1, n+1):
            ordered = list(permutations(range(1,n+1), k))
            assert ordered == sorted(ordered)
            for rank, literal in enumerate(ordered, 1):
                assert expected_indices(n,k,rank) == literal
                total += 1
    fixtures = cases()
    for _,k,r,a in fixtures:
        assert len(a) == k and len(set(a)) == k
        assert min(a) >= 1 and max(a) <= 47
        assert 1 <= r <= perm(47,k)
    assert total == 2360
    print(f"slice23-oracle=PASS exhaustive_small={total} goldens={len(fixtures)} "+
          "distinct_k=8 max_k=47 reference=independent-Python")


def emit_sql() -> None:
    print("-- Slice23 exact fixed arrays generated by independent Python rank oracle.")
    print("CREATE TEMP TABLE slice23_goldens(name text PRIMARY KEY,k integer,rank1 numeric,expected integer[]);")
    for name,k,r,answer in cases():
        array = ",".join(str(x) for x in answer)
        print(f"INSERT INTO slice23_goldens VALUES ('{name}',{k},{r},ARRAY[{array}]::integer[]);")


def emit_hashes() -> None:
    for name, k, rank, answer in cases():
        encoded = ",".join(map(str,answer)).encode("ascii")
        print(name, sha256(encoded).hexdigest())


if __name__ == "__main__":
    cli = argparse.ArgumentParser()
    group = cli.add_mutually_exclusive_group(required=True)
    group.add_argument("--self-test", action="store_true")
    group.add_argument("--emit-sql", action="store_true")
    group.add_argument("--emit-hashes", action="store_true")
    args = cli.parse_args()
    if args.self_test:
        self_test()
    elif args.emit_sql:
        emit_sql()
    else:
        emit_hashes()
