#!/usr/bin/env python3
"""Slice25 QA-only PostgreSQL DP streaming candidate and independent arithmetic checks.

This file NEVER edits the canonical production SQL. It transforms a copy for isolated
PostgreSQL jobs and preserves the original function interface and all other bytes.
"""
from __future__ import annotations

import argparse
import itertools
import math
import random
from pathlib import Path

SOURCE = Path('sql/24_stage02_month_weaving.sql')
OLD = '''        WITH RECURSIVE prefix(t,choose_factor,partial_sum) AS (
            SELECT 0,1::numeric,previous_row[h]
            UNION ALL
            SELECT t+1,
                   div(choose_factor*(t+h-1),t+1),
                   partial_sum + previous_row[t+h+1] *
                     div(choose_factor*(t+h-1),t+1)
            FROM prefix
            WHERE t<tmax
        )
        SELECT array_agg(partial_sum ORDER BY t) INTO new_row FROM prefix;'''
NEW = '''        -- QA-only candidate: read each previous-row item once by ordinality,
        -- then accumulate exact integer weighted contributions in t order.
        -- Coefficient C(t+h-2,h-2) is generated by the original recurrence.
        WITH RECURSIVE choose_coeff(t,choose_factor) AS (
            SELECT 0,1::numeric
            UNION ALL
            SELECT t+1,div(choose_factor*(t+h-1),t+1)
            FROM choose_coeff
            WHERE t<tmax
        ), weighted AS (
            SELECT c.t, c.choose_factor*u.val AS contribution
            FROM choose_coeff AS c
            JOIN unnest(previous_row) WITH ORDINALITY AS u(val,ordinal)
              ON u.ordinal=c.t+h
        ), rolling AS (
            SELECT t,
                   sum(contribution) OVER
                     (ORDER BY t ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)
                     AS partial_sum
            FROM weighted
        )
        SELECT array_agg(partial_sum ORDER BY t) INTO new_row FROM rolling;'''


def original_dp(lengths: tuple[int, ...]) -> tuple[tuple[int, ...], ...]:
    """Model original SELECT's indexed prefix recurrence, without PostgreSQL."""
    tmax = sum(n-1 for n in lengths)
    previous = [1]*(tmax+1)
    out = []
    for h in reversed(lengths):
        tmax -= h-1
        choose = 1
        subtotal = 0
        nxt = []
        for t in range(tmax+1):
            if t:
                numerator = choose*(t+h-2)
                assert numerator % t == 0
                choose = numerator//t
            subtotal += previous[t+h-1]*choose
            nxt.append(subtotal)
        previous = nxt
        out.append(tuple(nxt))
    return tuple(out)


def independent_dp(lengths: tuple[int, ...]) -> tuple[tuple[int, ...], ...]:
    """Independent binomial summation; no coefficient recurrence or indexing model."""
    n = sum(x-1 for x in lengths)
    values = tuple(1 for _ in range(n+1))
    result = []
    for h in reversed(lengths):
        n -= h-1
        contributions = tuple(v*math.comb(t+h-2,h-2)
                              for t,v in enumerate(values[h-1:h+n]))
        assert len(contributions) == n+1
        subtotal = 0
        row = []
        for term in contributions:
            subtotal += term
            row.append(subtotal)
        values = tuple(row)
        result.append(values)
    return tuple(result)


def check_math() -> int:
    samples = list(itertools.chain.from_iterable(
        itertools.product(range(2,6), repeat=k) for k in range(1,5)))
    rng = random.Random(20261121)
    samples.extend(tuple(rng.randint(2,9) for _ in range(rng.randint(1,8)))
                   for _ in range(500))
    for i, lengths in enumerate(samples,1):
        old = original_dp(lengths)
        expected = independent_dp(lengths)
        assert old == expected, f'case={i} lengths={lengths}'
        assert old[-1][0] >= 1
    print(f'SLICE25_DP_STREAM_ARITHMETIC={len(samples)}/{len(samples)} PASS')
    return len(samples)


def build_candidate(source: str) -> str:
    assert source.count(OLD) == 1, 'source block changed; refuse blind transform'
    assert source.count('CREATE OR REPLACE FUNCTION pastafari_sql_tamil.month_weaving_ranked(')==1
    candidate = source.replace(OLD,NEW,1)
    assert candidate.replace(NEW,OLD,1) == source, 'nonlocal source mutation'
    assert candidate.count('unnest(previous_row) WITH ORDINALITY') == 1
    return candidate


def main() -> None:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--self-test',action='store_true')
    p.add_argument('--write-candidate',type=Path)
    a=p.parse_args()
    if not (a.self_test or a.write_candidate):
        p.error('provide --self-test or --write-candidate')
    if a.self_test:
        check_math()
        stub = 'CREATE OR REPLACE FUNCTION pastafari_sql_tamil.month_weaving_ranked(\n' + OLD
        assert build_candidate(stub).replace(NEW, OLD, 1) == stub
        for broken in (stub.replace(OLD, ''), stub + OLD):
            try:
                build_candidate(broken)
            except AssertionError:
                pass
            else:
                raise AssertionError('source block lock failed')
        print('SLICE25_DP_STREAM_SINGLE_BLOCK_LOCK=PASS')
        print('SLICE25_DP_STREAM_POSTGRESQL=NOT_EXECUTED')
    if a.write_candidate:
        original=SOURCE.read_text(encoding='utf-8')
        candidate=build_candidate(original)
        a.write_candidate.parent.mkdir(parents=True, exist_ok=True)
        a.write_candidate.write_text(candidate,encoding='utf-8')
        print('SLICE25_DP_STREAM_TRANSFORM=EXACT_ONE_BLOCK STATIC_PASS')
        print(f'SLICE25_DP_STREAM_CANDIDATE={a.write_candidate}')
        print('SLICE25_DP_STREAM_PRODUCTION_SOURCE=UNCHANGED')

if __name__=='__main__':
    main()
