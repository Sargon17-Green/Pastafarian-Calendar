function run_stage55_real_year_lazy_joint_two_step()
% Natywny eksperyment: JEDEN wspólny licznik BigInt przy pierwszym
% rozgałęzieniu. Pełny wektor produkcyjnych długości roku 5000,
% lecz tylko dwie pierwsze litery: NIE zakończony Stage 55.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>
L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
   97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
   97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
assert(numel(L)==45 && sum(L)==4244, ...
    'Zmieniono produkcyjny wektor miesięcy roku 5000.');
% Podstawowy rodzic ma dokładnie 6765 cyfr i zaczyna się od
% 128435... według niezależnego, pełnego BigInt-differential.
% Zatem 10^6764 jest legalną, wielką rangą wewnętrzną, która
% nie wymaga ponownego przeliczania parent DP.
rank=pastafari.BigInt(['1' repmat('0',1,6764)]);
started=tic;
[piece,c]=pastafari.unrankGeneralWeaveSuffixChunkLazyJoint( ...
    L,L,0,0,rank,2);
elapsed=toc(started);
digits=char(c.initialCount);
assert(numel(digits)==6765 && ...
    strcmp(digits(1:48), ...
        '128435193114812925064090423584532383357732237146') && ...
    strcmp(digits(end-47:end), ...
        '453013001591510258450282157845902129318401703800'), ...
    'Wspólny DP przeczy pełnej liczbie z niezależnego MATLAB-a.');
assert(numel(piece)==2 && piece(1)==1 && ...
    (piece(2)==1 || piece(2)==2) && ...
    ~c.done && c.stepsComputed==2 && ...
    sum(c.remaining)==4242 && c.closedUpTo==0 && ...
    c.openedUpTo==1+double(piece(2)==2) && ...
    c.rank>=pastafari.BigInt(1) && c.rank<=c.count && ...
    c.initialCount>=rank, ...
    'Wybór na drugim dniu stracił legalny zakres/rangę.');
if piece(2)==1
    assert(isequal(c.remaining(1:2),[113 108]));
else
    assert(isequal(c.remaining(1:2),[114 107]));
end
fprintf(['STAGE_55_REAL_YEAR_LAZY_TWO_STEP_PASS ', ...
    'MONTHS=45 DAYS=4244 STEPS=2 FIRST=%d SECOND=%d ', ...
    'SECONDS=%.3f DIGITS=%d REMAINING_DAYS=%d\n'], ...
    piece(1),piece(2),elapsed,numel(digits),sum(c.remaining));
fprintf('STAGE_55_REAL_YEAR_LAZY_EXPERIMENTAL_PASS\n');
end
