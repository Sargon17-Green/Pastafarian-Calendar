function run_stage55_real_year_inner_cursor_resume_fifth()
% Etap 55: bounded FIFTH DAY for real year-5000 middle lexical rank.
% Input is SHA-pinned previous three-day cursor. No full weaving or Oracle.
root=fileparts(fileparts(mfilename('fullpath')));
srcDir=fullfile(root,'src');
addpath(srcDir);
srcGuard=onCleanup(@() rmpath(srcDir)); %#ok<NASGU>
logs=fullfile(root,'logs');
if exist(logs,'dir')~=7, mkdir(logs); end
diary(fullfile(logs,'STAGE55_REAL_YEAR_INNER_CURSOR_FIFTH_NATIVE.log'));
diaryGuard=onCleanup(@() diary('off')); %#ok<NASGU>
file=fullfile(logs,'STAGE55_REAL_YEAR_INNER_CURSOR_AFTER_4.json');
assert(exist(file,'file')==2,'Stage55:ThreeDaySourceMissing');
f=jsondecode(fileread(fullfile(root,'tests','fixtures', ...
    'stage55_year5000_appendix_a_metadata.json')));
L=double(f.month_lengths(:).');
assert(f.year==5000 && numel(L)==45 && sum(L)==4244, ...
    'Stage55:Year5000LengthsMismatch');
t=tic;
[original,previous]=pastafari.restoreExactWeaveCursorJson(fileread(file));
restoreSeconds=toc(t);
expected=L;
expected(1:4)=expected(1:4)-1;
one=pastafari.BigInt(1);
assert(isequal(original,L) && isequal(previous.remaining,expected) && ...
    previous.stepsComputed==4 && previous.openedUpTo==4 && ...
    previous.closedUpTo==0 && ~previous.done && ...
    sum(previous.remaining)==4240 && ...
    previous.rank>=one && previous.rank<=previous.count, ...
    'Stage55:ThreeDayCheckpointMismatch');
fprintf('STAGE55_MIDDLE_FIFTH_RESTORE_PASS SECONDS=%.3f COUNT_DIGITS=%d\n', ...
    restoreSeconds,numel(char(previous.count)));
t=tic;
[letter,next]=pastafari.unrankGeneralWeaveSuffixChunkAdjoint( ...
    original,previous.remaining,previous.openedUpTo, ...
    previous.closedUpTo,previous.rank,1);
chooseSeconds=toc(t);
assert(numel(letter)==1 && letter>=1 && letter<=45 && ...
    next.stepsComputed==1 && next.initialCount==previous.count && ...
    sum(next.remaining)==4239 && ~next.done && ...
    next.rank>=one && next.rank<=next.count, ...
    'Stage55:FifthDaySelectionMismatch');
n=previous.remaining(letter);
assert(n>0 && (n<L(letter) || letter==previous.openedUpTo+1) && ...
    (n~=1 || letter==previous.closedUpTo+1), ...
    'Stage55:FifthDayIllegalLetter');
replay=previous.remaining;
replay(letter)=replay(letter)-1;
assert(isequal(replay,next.remaining) && ...
    next.openedUpTo==previous.openedUpTo+double(n==L(letter)) && ...
    next.closedUpTo==previous.closedUpTo+double(n==1), ...
    'Stage55:FifthDayFrontierMismatch');
fprintf('STAGE55_MIDDLE_FIFTH_LETTER PREFIX=[1 2 3 4 %d] REMAINING=4240 SECONDS=%.3f\n', ...
    letter,chooseSeconds);
t=tic;
recount=pastafari.countWholeWeavingSuffixByFirstEndpoint( ...
    next.remaining,next.openedUpTo,next.closedUpTo);
recountSeconds=toc(t);
assert(recount==next.count && next.count<=previous.count, ...
    'Stage55:FifthDayIndependentCountMismatch');
next.stepsComputed=previous.stepsComputed+1;
dest=fullfile(logs,'STAGE55_REAL_YEAR_INNER_CURSOR_AFTER_5.json');
body=pastafari.serializeExactWeaveCursorJson(original,next);
[fid,message]=fopen(dest,'w','n','UTF-8');
assert(fid>=0,'Stage55:FifthDayCheckpointOpen',message);
guard=onCleanup(@() fclose(fid)); %#ok<NASGU>
assert(fwrite(fid,body,'char')==numel(body), ...
    'Stage55:FifthDayCheckpointTruncated');
clear guard
assert(strcmp(fileread(dest),body) && next.stepsComputed==5, ...
    'Stage55:FifthDayCheckpointReadback');
fprintf('STAGE55_MIDDLE_FIFTH_RECOUNT_PASS COUNT_DIGITS=%d SECONDS=%.3f\n', ...
    numel(char(recount)),recountSeconds);
fprintf('STAGE55_REAL_YEAR_MIDDLE_RANK_FIFTH_DAY_NATIVE_PASS YEAR=5000 MONTHS=45 DAYS=4244 PREFIX=[1 2 3 4 %d] REMAINING=4240\n',letter);
fprintf('STAGE55_FULL_INTERIOR_WEAVE_NOT_VERIFIED\n');
fprintf('STAGE55_CANONICAL_FIVE_FIELD_ORACLE_NOT_VERIFIED\n');
fprintf('STAGE55_CROSS_ENGINE_SOAK_NOT_VERIFIED\n');
fprintf('STAGE55_FINAL_STAGE_PASS_NOT_VERIFIED\n');
end
