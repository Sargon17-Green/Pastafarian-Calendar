#!/usr/bin/env python3
"""Differentially verify large-family weave rank/offset witnesses.

The expected witnesses are generated by the separate JavaScript BigInt audit.
This script imports the exact committed Python oracle and verifies every
month/day pair for every rank and calendar offset in that fixture.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ORACLE_PATH = ROOT / "tests" / "stage02_calendar_weave_independent_oracle.py"
WITNESS_PATH = ROOT / "artifacts" / "stage02-weave-large-rank-offset-audit-20261125.md"
EXPECTED_ORACLE_BLOB = "5793a3a9e310f6515d33fd86362324ba0f577a34"
EXPECTED_WITNESS_BLOB = "102f32ed6ac4db427cf055bb8c75d4bf4acc9e53"


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def git_blob_sha(path: Path) -> str:
    payload = path.read_bytes()
    header = f"blob {len(payload)}\0".encode("ascii")
    return hashlib.sha1(header + payload).hexdigest()


def load_oracle():
    actual_blob = git_blob_sha(ORACLE_PATH)
    require(actual_blob == EXPECTED_ORACLE_BLOB,
            f"Python oracle blob changed: {actual_blob}")
    spec = importlib.util.spec_from_file_location(
        "stage02_calendar_weave_independent_oracle", ORACLE_PATH
    )
    require(spec is not None and spec.loader is not None,
            "cannot load exact-source Python oracle")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module, actual_blob


def load_witnesses() -> tuple[dict, str]:
    actual_blob = git_blob_sha(WITNESS_PATH)
    require(actual_blob == EXPECTED_WITNESS_BLOB,
            f"JavaScript witness report blob changed: {actual_blob}")
    content = WITNESS_PATH.read_text(encoding="utf-8")
    match = re.search(r"\x60{3}json\s*(\{.*?\})\s*\x60{3}", content, re.DOTALL)
    require(match is not None, "missing JSON witness block")
    data = json.loads(match.group(1))
    require(data.get("project") == "PC-BRANCH-WAT-SPANISH",
            "wrong project in witness fixture")
    require(data.get("baseline") == "dae7856af5ca5664b0e493af22cef2aadf40a794",
            "wrong source baseline in witness fixture")
    require(data.get("ranks") == 202, "wrong expected rank count")
    require(data.get("offsets") == 3237, "wrong expected offset count")
    require(data.get("invalid") == 12, "wrong expected invalid-rank count")
    return data, actual_blob


def main() -> None:
    oracle, oracle_blob = load_oracle()
    witnesses, witness_blob = load_witnesses()

    rank_count = 0
    offset_count = 0
    invalid_count = 0
    full_words_checked = 0

    for case in witnesses["cases"]:
        lengths = case["lengths"]
        family_size = int(case["count"])
        require(oracle.completion_table(lengths)[0][0] == family_size,
                f"family cardinality mismatch: {lengths}")

        for witness in case["probes"]:
            rank = int(witness["rank"])
            expected_offsets = witness["offsets"]
            expected_word = [int(x) for x in witness["word"].split(",")]
            require(len(expected_offsets) == sum(lengths),
                    f"wrong offset fixture length: {lengths=} {rank=}")
            require(len(expected_word) == sum(lengths),
                    f"wrong word fixture length: {lengths=} {rank=}")

            full = oracle.unrank_weave_at(
                lengths, rank, sum(lengths) - 1, full=True
            )
            require(full["family_size"] == str(family_size),
                    f"full family size mismatch: {lengths=} {rank=}")
            require(full["word"] == expected_word,
                    f"full word mismatch: {lengths=} {rank=}")
            full_words_checked += 1

            for target, expected_pair in enumerate(expected_offsets):
                actual = oracle.unrank_weave_at(lengths, rank, target)
                actual_pair = [actual["month_id"], actual["day_in_month"]]
                require(actual_pair == expected_pair,
                        f"rank/offset mismatch: {lengths=} {rank=} {target=} "
                        f"expected={expected_pair} actual={actual_pair}")
                require(actual["family_size"] == str(family_size),
                        f"offset family size mismatch: {lengths=} {rank=} {target=}")
                require(actual["target_offset_zero_based"] == target,
                        f"offset identity mismatch: {lengths=} {rank=} {target=}")
                offset_count += 1
            rank_count += 1

        for bad_rank in (0, family_size + 1):
            try:
                oracle.unrank_weave_at(lengths, bad_rank, 0)
            except AssertionError:
                invalid_count += 1
            else:
                raise AssertionError(
                    f"invalid rank accepted: {lengths=} {bad_rank=}"
                )

    require(rank_count == witnesses["ranks"], "rank total mismatch")
    require(offset_count == witnesses["offsets"], "offset total mismatch")
    require(invalid_count == witnesses["invalid"], "invalid-rank total mismatch")
    print(json.dumps({
        "project_id": "PC-BRANCH-WAT-SPANISH",
        "mode": "exact_source_python_vs_independent_javascript_witnesses",
        "python_oracle_git_blob": oracle_blob,
        "javascript_witness_git_blob": witness_blob,
        "ranks_checked": rank_count,
        "full_words_checked": full_words_checked,
        "offsets_checked": offset_count,
        "invalid_ranks_rejected": invalid_count,
        "families_checked": len(witnesses["cases"]),
        "python_differential_pass": True,
        "native_pass": False,
        "stage02_accepted": False
    }, sort_keys=True))


if __name__ == "__main__":
    main()
