function run_stage55_real_year_binary_four()
% Pilot only: genuine 45-month year, all initially unopened, rank 10^6764.
% Compare the first four symbols with independently native-verified
% year-5000 eight-day joint unrank; recount final suffix separately.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>
L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
   97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
   97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
rank=pastafari.BigInt(['1' repmat('0',1,6764)]);
assert(numel(L)==45 && sum(L)==4244);
timer=tic;
[word,c]=pastafari.unrankGeneralWeaveSuffixChunkBinary( ...
    L,L,0,0,rank,4);
elapsed=toc(timer);
assert(isequal(word,[1 2 3 4]) && ...
    c.openedUpTo==4 && c.closedUpTo==0 && ...
    sum(c.remaining)==4240 && ~c.done && ...
    c.rank>=pastafari.BigInt(1) && c.rank<=c.count && ...
    numel(char(c.initialCount))==6765, ...
    'Real initial unopened rank differs from independently proven prefix.');
fprintf(['STAGE_55_BINARY_REAL_YEAR_FOUR_UNRANK_PASS ', ...
    'STEPS=4 REMAINING=4240 SECONDS=%.3f\n'],elapsed);
timer=tic;
independent=pastafari.countWholeWeavingSuffixByFirstEndpoint( ...
    c.remaining,c.openedUpTo,c.closedUpTo);
assert(independent==c.count, ...
    'Binary selected child count differs from separate exact suffix DP.');
fprintf(['STAGE_55_BINARY_REAL_YEAR_FOUR_CHILD_COUNT_PASS ', ...
    'DIGITS=%d SECONDS=%.3f\n'],numel(char(independent)),toc(timer));
fprintf('STAGE_55_BINARY_REAL_YEAR_FOUR_EXPERIMENTAL_PASS\n');
end
