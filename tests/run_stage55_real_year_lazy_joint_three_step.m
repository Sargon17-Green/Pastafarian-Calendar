function run_stage55_real_year_lazy_joint_three_step()
% EXPERIMENT ONLY: first THREE exact 1-indexed lexical symbols for a
% true interior rank in the real production-selected 45-month 4244-day
% year-5000 vector. No production route, oracle or main modifications.
% Crucially, INDEPENDENTLY recount the resulting 4241-day suffix using
% the separate first-endpoint BigInt DP, instead of relying only on
% the joint DP's returned child block count.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>

L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
   97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
   97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
assert(numel(L)==45 && sum(L)==4244);
one=pastafari.BigInt(1);
% Known strict interior of the independently verified real-year
% 6765-digit count (first digits 128435..., last 453013...).
rank=pastafari.BigInt(['1' repmat('0',1,6764)]);
timer=tic;
[word,c]=pastafari.unrankGeneralWeaveSuffixChunkLazyJoint( ...
    L,L,0,0,rank,3);
unrankSeconds=toc(timer);

n=char(c.initialCount);
assert(numel(n)==6765 && ...
    strcmp(n(1:48), ...
        '128435193114812925064090423584532383357732237146') && ...
    strcmp(n(end-47:end), ...
        '453013001591510258450282157845902129318401703800'), ...
    'The initial joint parent count disagrees with prior dual-DP count.');
assert(numel(word)==3 && isequal(word(1:2),[1 2]) && ...
    any(word(3)==[1 2 3]) && ...
    c.openedUpTo==(2+double(word(3)==3)) && ...
    c.closedUpTo==0 && ...
    c.stepsComputed==3 && ~c.done && ...
    sum(c.remaining)==4241 && ...
    c.rank>=one && c.rank<=c.count && ...
    c.initialCount>=rank, ...
    'Incorrect exact third letter or invalid continued rank.');

expected=L;
for j=word
    expected(j)=expected(j)-1;
end
assert(isequal(c.remaining,expected), ...
    'Returned continuation lost or duplicated a month occurrence.');
fprintf(['STAGE_55_REAL_YEAR_THREE_STEP_JOINT_PREFIX_PASS ', ...
    'MONTHS=45 DAYS=4244 LETTERS=%s ', ...
    'UNRANK_SECONDS=%.3f REMAINING=%d CHILD_DIGITS=%d\n'], ...
    mat2str(word),unrankSeconds,sum(c.remaining),numel(char(c.count)));

% SEPARATE recurrence: count every completion for precisely the cursor
% after 3 days and compare the WHOLE BigInt child block exactly.
timer=tic;
independent=pastafari.countWholeWeavingSuffixByFirstEndpoint( ...
    c.remaining,c.openedUpTo,c.closedUpTo);
checkSeconds=toc(timer);
assert(independent==c.count, ...
    'Joint third-child block differs from independent exact suffix DP.');
fprintf(['STAGE_55_REAL_YEAR_THIRD_CHILD_EXACT_DIFFERENTIAL_PASS ', ...
    'REMAINING=4241 SECONDS=%.3f DIGITS=%d\n'], ...
    checkSeconds,numel(char(independent)));
fprintf('STAGE_55_REAL_YEAR_THREE_STEP_EXPERIMENTAL_PASS\n');
end
