function run_stage55_real_year_8_day_unopened()
% Experimental genuine 4244-day year, 45 initially unopened months.
% Four independently recounted two-day chunks for an arbitrary INTERIOR
% 6765-digit rank. Does not change production or normative_oracle.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>

L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
   97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
   97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
assert(numel(L)==45 && sum(L)==4244);
one=pastafari.BigInt(1);
initialRank=pastafari.BigInt(['1' repmat('0',1,6764)]);
assert(numel(char(initialRank))==6765);
R=L; opened=0; closed=0; rank=initialRank;
word=zeros(1,8);
checkpoint4=struct();
previousCount=pastafari.BigInt(0);
start=tic;
for part=1:4
    timer=tic;
    [letters,cursor]=pastafari.unrankGeneralWeaveSuffixChunkLazyJoint( ...
        L,R,opened,closed,rank,2);
    assert(numel(letters)==2 && cursor.stepsComputed==2 && ...
        sum(cursor.remaining)==4244-2*part && ...
        ~cursor.done && cursor.rank>=one && cursor.rank<=cursor.count && ...
        cursor.closedUpTo<=cursor.openedUpTo && ...
        cursor.openedUpTo<=45, ...
        'Native exact two-day cursor lost a year-5000 invariant.');
    if part>1
        assert(cursor.initialCount==previousCount, ...
            'Independently recounted chunk parent differs from prior child.');
    else
        assert(numel(char(cursor.initialCount))==6765 && ...
            cursor.initialCount>=initialRank, ...
            'The complete real-year family/count is inconsistent.');
    end
    word(2*part-1:2*part)=letters;
    if part==2
        checkpoint4=cursor;
    end
    R=cursor.remaining;
    opened=cursor.openedUpTo;
    closed=cursor.closedUpTo;
    rank=cursor.rank;
    previousCount=cursor.count;
    fprintf(['STAGE_55_REAL_YEAR_UNOPENED_8_PROGRESS ', ...
        'DAY=%d OF=8 OPENED=%d CLOSED=%d REMAINING=%d ', ...
        'CHUNK_SECONDS=%.3f TOTAL_SECONDS=%.3f\n'], ...
        2*part,opened,closed,sum(R),toc(timer),toc(start));
end
assert(isequal(word(1:3),[1 2 3]) && ...
    all(word>=1 & word<=45) && ...
    opened>=3 && opened<45 && closed>=0 && ...
    sum(R)==4236 && ~cursor.done, ...
    'Eight real-year days disagree with verified three-day opening prefix.');
expected=L;
for monthId=word
    expected(monthId)=expected(monthId)-1;
end
assert(isequal(expected,R), ...
    'The eight-day word lost or duplicated an occurrence.');
fprintf(['STAGE_55_REAL_YEAR_UNOPENED_8_UNRANK_PASS ', ...
    'DAYS=8 REMAINING=4236 OPENED=%d CLOSED=%d ', ...
    'SECONDS=%.3f\n'],opened,closed,toc(start));

% Reverse-direction exact interval for the first four opening days,
% using a separately verified rank-general algorithm.
timer=tic;
[lo,hi,inverse]=pastafari.rankGeneralWeavePrefix( ...
    L,L,0,0,word(1:4),'joint');
assert(lo<=initialRank && initialRank<=hi && ...
    hi-lo+one==checkpoint4.count && ...
    initialRank-lo+one==checkpoint4.rank, ...
    'Four-day exact reverse rank differs from unrank continuation.');
% Explicitly compare the complete initial family against a separately
% known first-chunk count, not the fourth chunk parent.
[~,initialCursor]=pastafari.unrankGeneralWeaveSuffixChunkLazyJoint( ...
    L,L,0,0,initialRank,0);
assert(inverse.totalCount==initialCursor.count, ...
    'The inverse total contradicts an independent native parent recount.');
fprintf(['STAGE_55_REAL_YEAR_UNOPENED_8_FIRST4_INVERSE_PASS ', ...
    'STEPS=4 SECONDS=%.3f\n'],toc(timer));

% Independent recurrence: recount ALL possible 4236-day completions
% without trusting the joint first-letter blocks that selected this word.
timer=tic;
independent=pastafari.countWholeWeavingSuffixByFirstEndpoint( ...
    R,opened,closed);
assert(independent==cursor.count && ...
    rank>=one && rank<=independent, ...
    'Joint unrank child count contradicts independent exact DP.');
fprintf(['STAGE_55_REAL_YEAR_UNOPENED_8_INDEPENDENT_COUNT_PASS ', ...
    'REMAINING=4236 DIGITS=%d SECONDS=%.3f\n'], ...
    numel(char(independent)),toc(timer));

% BigInts in JSON are strings; restore independently recounts the
% entire state. Keep the final unrank cursor separate from a complete word.
saved=struct('remaining',R,'openedUpTo',opened, ...
    'closedUpTo',closed,'rank',rank,'count',cursor.count, ...
    'done',false,'stepsComputed',8);
json=pastafari.serializeExactWeaveCursorJson(L,saved);
assert(contains(json,'"rankDecimal":"') && ...
    contains(json,'"countDecimal":"'), ...
    'JSON must never round large rank/count through a numeric field.');
[restoredL,restored]=pastafari.restoreExactWeaveCursorJson(json);
assert(isequal(restoredL,L) && isequal(restored.remaining,R) && ...
    restored.openedUpTo==opened && restored.closedUpTo==closed && ...
    restored.rank==rank && restored.count==cursor.count && ...
    restored.stepsComputed==8 && ~restored.done, ...
    'Eight-day portable JSON did not restore the verified frontier.');
fprintf('STAGE_55_REAL_YEAR_UNOPENED_8_CHECKPOINT_PASS\n');
fprintf('STAGE_55_REAL_YEAR_UNOPENED_8_EXPERIMENTAL_PASS\n');
end
