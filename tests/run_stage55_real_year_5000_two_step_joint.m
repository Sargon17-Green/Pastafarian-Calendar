function run_stage55_real_year_5000_two_step_joint()
% Exactly TWO first letters of the ACTUAL production-selected 5000-year
% month length vector. This tests the non-forced SECOND letter using
% the experimentally native-proven joint next-month BigInt DP.
% It neither computes the rest of the 4244-day weaving nor substitutes
% for the complete Stage54/55 normative-oracle comparison.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>
L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
   97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
   97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
assert(numel(L)==45 && sum(L)==4244, ...
    'Actual year-5000 month-length fixture changed.');
totalTimer=tic;
total=pastafari.countWholeWeavingSuffixByFirstEndpoint(L,0,0);
rank=total.floorDiv(pastafari.BigInt(2))+pastafari.BigInt(1);
assert(rank>pastafari.BigInt(1) && rank<=total, ...
    'Middle rank must be strictly interior to the legal family.');
fprintf(['STAGE_55_REAL_YEAR_TWO_STEP_COUNT_READY ', ...
    'MONTHS=45 DAYS=4244 SECONDS=%.3f DIGITS=%d\n'], ...
    toc(totalTimer),numel(char(total)));

% First symbol is forced to be month 1; SECOND is genuinely a choice
% between continuing month 1 and opening month 2. This cannot be
% validated by a sole forced-first-letter bijection.
unrankTimer=tic;
[piece,cursor]=pastafari.unrankGeneralWeaveSuffixChunk( ...
    L,L,0,0,rank,2,'joint');
seconds=toc(unrankTimer);
assert(numel(piece)==2 && piece(1)==1 && ...
    (piece(2)==1 || piece(2)==2) && ...
    cursor.openedUpTo==(1+double(piece(2)==2)) && ...
    cursor.closedUpTo==0 && ...
    sum(cursor.remaining)==4242 && ...
    cursor.stepsComputed==2 && ~cursor.done && ...
    cursor.rank>=pastafari.BigInt(1) && ...
    cursor.rank<=cursor.count, ...
    'Exact second-letter branching or resume cursor is invalid.');
if piece(2)==1
    assert(isequal(cursor.remaining(1:2),[113 108]));
else
    assert(isequal(cursor.remaining(1:2),[114 107]));
end
fprintf(['STAGE_55_REAL_YEAR_TWO_STEP_JOINT_PASS ', ...
    'MONTHS=45 DAYS=4244 STEPS=2 ', ...
    'FIRST=%d SECOND=%d SECONDS=%.3f REMAINING=%d ', ...
    'CURSOR_COUNT_DIGITS=%d\n'], ...
    piece(1),piece(2),seconds,sum(cursor.remaining), ...
    numel(char(cursor.count)));
fprintf('STAGE_55_REAL_YEAR_TWO_STEP_EXPERIMENTAL_PASS\n');
end
