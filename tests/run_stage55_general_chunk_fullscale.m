function run_stage55_general_chunk_fullscale()
% FULL-SIZED SYNTHETIC reference, EXACTLY one initial forced choice.
% This is NOT the actual production 5000-year month-length vector, and
% not a Stage54 production-vs-normative_oracle differential.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>

L=[108 repmat(94,1,44)];
assert(numel(L)==45 && sum(L)==4244);
start=tic;
count=pastafari.countWholeWeavingSuffixByFirstEndpoint(L,0,0);
rank=count.floorDiv(pastafari.BigInt(2))+pastafari.BigInt(1);
[piece,c]=pastafari.unrankGeneralWeaveSuffixChunk( ...
    L,L,0,0,rank,1);
duration=toc(start);
assert(isequal(piece,1) && c.stepsComputed==1 && ...
    c.openedUpTo==1 && c.closedUpTo==0 && ...
    isequal(c.remaining,[107 repmat(94,1,44)]) && ...
    c.rank==rank && c.count==count && ~c.done, ...
    '4244-day forced first month lost the exact rank or count.');
digits=char(count);
assert(numel(digits)==6844 && ...
    strcmp(digits(1:48), ...
        '274324460241386716639660134170726950620695177088') && ...
    strcmp(digits(end-47:end), ...
        '924885822253633097338430639126334493274345601640'), ...
    '4244-day independent-count witness changed.');
fprintf(['STAGE_55_GENERAL_CHUNK_4244_FORCED_PASS ', ...
    'MONTHS=45 DAYS=4244 STEPS=1 SECONDS=%.3f ', ...
    'DIGITS=%d EXACT_RANK_KEPT=1\n'],duration,numel(digits));
end
