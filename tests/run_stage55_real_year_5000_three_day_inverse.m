function run_stage55_real_year_5000_three_day_inverse()
% Exact reverse-direction rank check on ACTUAL full unopened calendar
% year-5000 month lengths. Not synthetic, not all-open 4199-day suffix.
% Earlier native run 39945747252 independently unranked rank 10^6764
% to first letters [1 2 3] with an independent third-child recount.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>

L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
   97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
   97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
assert(numel(L)==45 && sum(L)==4244);
rank=pastafari.BigInt(['1' repmat('0',1,6764)]);
timer=tic;
[lo,hi,c]=pastafari.rankGeneralWeavePrefix( ...
    L,L,0,0,[1 2 3],'joint');
elapsed=toc(timer);
totalStr=char(c.totalCount);
assert(numel(totalStr)==6765 && ...
    strcmp(totalStr(1:48), ...
        '128435193114812925064090423584532383357732237146') && ...
    strcmp(totalStr(end-47:end), ...
        '453013001591510258450282157845902129318401703800'), ...
    'Initial real year 5000 count disagrees with independent DP witness.');
assert(lo<=rank && rank<=hi && ...
    hi-lo+pastafari.BigInt(1)==c.count && ...
    c.stepsComputed==3 && c.openedUpTo==3 && ...
    c.closedUpTo==0 && sum(c.remaining)==4241 && ...
    isequal(c.remaining(1:3),[114 107 118]) && ~c.done, ...
    'Three-day year-5000 prefix interval does not include known rank.');
fprintf(['STAGE_55_REAL_YEAR_5000_THREE_DAY_INVERSE_PASS ', ...
    'MONTHS=45 DAYS=4244 PREFIX=[1 2 3] ', ...
    'REMAINING=4241 SECONDS=%.3f DIGITS=%d\n'], ...
    elapsed,numel(totalStr));
fprintf('STAGE_55_REAL_YEAR_GENERAL_PREFIX_EXPERIMENTAL_PASS\n');
end
