function run_stage55_real_year_inner_cursor_resume()
% Stage55: continue the REAL year-5000 middle-rank cursor from
% run 40741372213's exact two-day checkpoint. No repetition of the
% cancelled 2+2 direct-reference experiment. No full-word/oracle claim.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>
L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
   97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
   97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
assert(numel(L)==45 && sum(L)==4244 && min(L)==25, ...
    'Stage55:RealYearFixtureChanged');
source=fullfile(root,'logs','STAGE55_REAL_YEAR_INNER_CURSOR_AFTER_2.json');
assert(exist(source,'file')==2,'Stage55:SourceArtifactMissing');
timer=tic;
[origin,previous]=pastafari.restoreExactWeaveCursorJson(fileread(source));
assert(isequal(origin,L) && previous.stepsComputed==2 && ...
    sum(previous.remaining)==4242 && ...
    previous.openedUpTo>=1 && previous.closedUpTo==0 && ...
    ~previous.done && previous.rank>=pastafari.BigInt(1) && ...
    previous.rank<=previous.count,'Stage55:TwoDayCheckpoint');
fprintf(['STAGE55_MIDDLE_RANK_TWO_DAY_CHECKPOINT_VERIFIED ', ...
    'STEPS=2 REMAINING=4242 SECONDS=%.3f\n'],toc(timer));

timer=tic;
[letter,next]=pastafari.unrankGeneralWeaveSuffixChunkAdjoint( ...
    origin,previous.remaining,previous.openedUpTo, ...
    previous.closedUpTo,previous.rank,1);
selectionSeconds=toc(timer);
assert(numel(letter)==1 && next.stepsComputed==1 && ...
    letter>=1 && letter<=numel(L) && ...
    sum(next.remaining)==4241 && ...
    next.rank>=pastafari.BigInt(1) && ...
    next.rank<=next.count && ~next.done && ...
    next.initialCount==previous.count, ...
    'Stage55:ResumedMiddleRankSelection');
replayed=previous.remaining;
multiplicity=replayed(letter);
assert(multiplicity>=1,'Stage55:ImpossibleChosenLetter');
replayed(letter)=replayed(letter)-1;
assert(isequal(replayed,next.remaining) && ...
    next.openedUpTo==previous.openedUpTo+double(multiplicity==L(letter)) && ...
    next.closedUpTo==previous.closedUpTo+double(multiplicity==1), ...
    'Stage55:ResumeFrontierMismatch');
fprintf(['STAGE55_MIDDLE_RANK_THIRD_DAY_SELECTED ', ...
    'LETTER=%d REMAINING=4241 SECONDS=%.3f\n'], ...
    letter,selectionSeconds);

% Independently verify the resulting exact child count using a
% separate scalar endpoint recurrence, not the adjoint block weights.
timer=tic;
recount=pastafari.countWholeWeavingSuffixByFirstEndpoint( ...
    next.remaining,next.openedUpTo,next.closedUpTo);
assert(recount==next.count, ...
    'Stage55:ResumeIndependentChildCountMismatch');
fprintf(['STAGE55_MIDDLE_RANK_THIRD_DAY_RECOUNT ', ...
    'DIGITS=%d SECONDS=%.3f\n'],numel(char(recount)),toc(timer));

next.stepsComputed=previous.stepsComputed+next.stepsComputed;
destination=fullfile(root,'logs', ...
    'STAGE55_REAL_YEAR_INNER_CURSOR_AFTER_3.json');
body=pastafari.serializeExactWeaveCursorJson(origin,next);
[fid,message]=fopen(destination,'w','n','UTF-8');
assert(fid>=0,'Stage55:ResumeCheckpointOpen',message);
guard=onCleanup(@() fclose(fid)); %#ok<NASGU>
assert(fwrite(fid,body,'char')==numel(body), ...
    'Stage55:ResumeCheckpointTruncated');
clear guard
assert(strcmp(fileread(destination),body) && ...
    next.stepsComputed==3,'Stage55:ResumeCheckpointWrite');
fprintf(['STAGE55_REAL_YEAR_MIDDLE_RANK_RESUME_ONE_DAY_PASS ', ...
    'VERIFIED_PREFIX_LENGTH=3 FULL_WORD=NOT_RUN ', ...
    'NORMATIVE_ORACLE=NOT_RUN STAGE55=OPEN\n']);
end
