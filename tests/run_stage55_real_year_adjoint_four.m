function run_stage55_real_year_adjoint_four()
% Real 4244-day, 45-month, all-unopened stage-55 rank 10^6764:
% exact adjoint first-letter blocks, full chosen four-letter inverse,
% and independent 4240-day child count. Unchanged normative oracle.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>
L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
    97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
    97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
rank=pastafari.BigInt(['1' repmat('0',1,6764)]);
assert(numel(L)==45 && sum(L)==4244);
timer=tic;
[word,c]=pastafari.unrankGeneralWeaveSuffixChunkAdjoint( ...
    L,L,0,0,rank,4);
secs=toc(timer);
assert(isequal(word,[1 2 3 4]) && ...
    c.openedUpTo==4 && c.closedUpTo==0 && ...
    sum(c.remaining)==4240 && ~c.done && ...
    c.rank>=pastafari.BigInt(1) && c.rank<=c.count && ...
    numel(char(c.initialCount))==6765, ...
    'The adjoint exact rank differs from the verified year-5000 word.');
fprintf(['STAGE_55_REAL_YEAR_ADJOINT_FOUR_UNRANK_PASS ', ...
    'STEPS=4 REMAINING=4240 SECONDS=%.3f\n'],secs);
timer=tic;
independent=pastafari.countWholeWeavingSuffixByFirstEndpoint( ...
    c.remaining,c.openedUpTo,c.closedUpTo);
assert(independent==c.count, ...
    'Adjoint residual parent differs from independent exact count.');
fprintf(['STAGE_55_REAL_YEAR_ADJOINT_FOUR_CHILD_PASS ', ...
    'DIGITS=%d SECONDS=%.3f\n'], ...
    numel(char(independent)),toc(timer));
fprintf('STAGE_55_REAL_YEAR_ADJOINT_FOUR_EXPERIMENTAL_PASS\n');
end
