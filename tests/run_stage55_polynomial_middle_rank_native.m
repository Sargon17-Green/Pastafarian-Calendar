function run_stage55_polynomial_middle_rank_native()
% Stage55: full 4244-symbol middle-rank differential for the EXPERIMENTAL
% polynomial family. This deliberately does NOT call the production
% WholeMonthWeavingFamily, MonthWeavingDPPatchWrapper or final integration.
%
% Independent references:
% - the exact 45 month lengths were rederived by the separate source-rank /
%   cutlet / Polish-catalog oracle (run 45691066424);
% - the complete middle word and its 4244 prefix intervals were verified
%   by the independent C++17/GMP inverse-rank verifier (run 45686680226).
%
% This test can validate a scalable candidate without changing production.
% It is NOT the Stage54 production differential or Stage55 acceptance.

here = fileparts(mfilename('fullpath'));
root = fileparts(here);
src = fullfile(root, 'src');
addpath(src);
pathCleanup = onCleanup(@() rmpath(src)); %#ok<NASGU>

fixturePath = fullfile(root, 'tests', 'fixtures', ...
    'stage55_year5000_appendix_a_metadata.json');
wordPath = fullfile(root, 'tests', 'fixtures', ...
    'stage55_year5000_middle_word.json');
assert(exist(fixturePath, 'file') == 2 && exist(wordPath, 'file') == 2, ...
    'Stage55:PolynomialMiddleFixtureMissing');

metadata = jsondecode(fileread(fixturePath));
lengths = double(metadata.month_lengths(:).');
expectedWord = double(jsondecode(fileread(wordPath)));
expectedWord = expectedWord(:).';

candidateCommit = getenv('GITHUB_SHA');
assert(~isempty(candidateCommit), 'Stage55:PolynomialMiddleCommitMissing');
assert(metadata.year == 5000 && metadata.months == 45 && ...
    numel(lengths) == 45 && sum(lengths) == 4244 && ...
    min(lengths) == 25 && max(lengths) == 122 && ...
    numel(expectedWord) == 4244, ...
    'Stage55:PolynomialMiddleFixtureChanged');

if exist(fullfile(root, 'logs'), 'dir') ~= 7
    mkdir(fullfile(root, 'logs'));
end

fprintf(['STAGE55_POLYNOMIAL_MIDDLE_BEGIN SHA=%s MONTHS=%d DAYS=%d ', ...
    'CANDIDATE_ONLY=1 PRODUCTION_ROUTE=NOT_RUN\n'], ...
    candidateCommit, numel(lengths));

% Phase 1: exact total count. The C++ verifier independently pins both
% the 6765-digit total and the 6764-digit one-based middle rank.
countTimer = tic;
family = pastafari.WholeMonthWeavingFamilyPolynomial(lengths);
total = family.count();
countSeconds = toc(countTimer);
one = pastafari.BigInt(1);
rank = total.floorDiv(pastafari.BigInt(2)) + one;

assert(total > one && numel(char(total)) == 6765 && ...
    numel(char(rank)) == 6764, ...
    'Stage55:PolynomialMiddleCountShape');
writeExactText(fullfile(root, 'logs', ...
    'STAGE55_POLYNOMIAL_MIDDLE_ROOT_COUNT.txt'), char(total));
writeExactText(fullfile(root, 'logs', ...
    'STAGE55_POLYNOMIAL_MIDDLE_RANK.txt'), char(rank));
fprintf(['STAGE55_POLYNOMIAL_MIDDLE_COUNT_PASS DIGITS=%d ', ...
    'RANK_DIGITS=%d SECONDS=%.3f\n'], ...
    numel(char(total)), numel(char(rank)), countSeconds);
enforceElapsed(countTimer, 240, 'exact root count');

% Phase 2: full native MATLAB unrank through the experimental polynomial
% family. The independent C++/GMP word is the exact comparison oracle.
unrankTimer = tic;
actualWord = family.itemAt1(rank);
unrankSeconds = toc(unrankTimer);
enforceElapsed(unrankTimer, 2400, 'full middle-rank unrank');

family.verifyWord(actualWord);
assert(isrow(actualWord) && numel(actualWord) == 4244 && ...
    isequal(actualWord, expectedWord), ...
    'Stage55:PolynomialMiddleWordMismatch');

% Repeat the terminal legality checks in this test, independently of the
% candidate class's own verifyWord method.
first = zeros(1, numel(lengths));
last = zeros(1, numel(lengths));
for month = 1:numel(lengths)
    positions = find(actualWord == month);
    assert(numel(positions) == lengths(month), ...
        'Stage55:PolynomialMiddleMultiplicityMismatch');
    first(month) = positions(1);
    last(month) = positions(end);
end
assert(all(diff(first) > 0) && all(diff(last) > 0), ...
    'Stage55:PolynomialMiddleOrderMismatch');

wordText = jsonencode(actualWord);
writeExactText(fullfile(root, 'logs', ...
    'STAGE55_POLYNOMIAL_MIDDLE_NATIVE_WORD.json'), wordText);

report = struct( ...
    'project_id', 'PC-BRANCH-MATLAB-POLSKI', ...
    'candidate_commit', candidateCommit, ...
    'native_matlab_version', version, ...
    'native_matlab_release', version('-release'), ...
    'candidate_class', 'pastafari.WholeMonthWeavingFamilyPolynomial', ...
    'production_class_used', false, ...
    'production_route_used', false, ...
    'month_count', numel(lengths), ...
    'total_days', sum(lengths), ...
    'root_count_digits', numel(char(total)), ...
    'root_count_sha256_expected', ...
        'c0c08ac89c8faaaf589d1b3e076fe1e96405f2ad7172a15efa9d028fb43fb6f8', ...
    'middle_rank_digits', numel(char(rank)), ...
    'middle_rank_sha256_expected', ...
        'cd5ce4036fc8e99355a4bab5d48c3db473422083d035df5e0af25297be1be3b6', ...
    'middle_rank_policy', 'floor(T/2)+1', ...
    'word_symbols', numel(actualWord), ...
    'word_matches_independent_cpp_fixture', true, ...
    'full_word_sha256_expected', ...
        '82042fef5a65cc8b08120d069fa9d8f31c05e6761040f82c3341328ded9b44e5', ...
    'count_seconds', countSeconds, ...
    'unrank_seconds', unrankSeconds, ...
    'stage55_accepted', false, ...
    'last_completed_stage', 54, ...
    'scope', ['Experimental polynomial candidate only; no production ', ...
        'integration or final Stage55 acceptance.']);
writeExactText(fullfile(root, 'logs', ...
    'STAGE55_POLYNOMIAL_MIDDLE_REPORT.json'), jsonencode(report));

fprintf(['STAGE55_POLYNOMIAL_MIDDLE_FULL_WORD_PASS MONTHS=%d DAYS=%d ', ...
    'RANK_POLICY=FLOOR_T_OVER_2_PLUS_1 COUNT_SECONDS=%.3f ', ...
    'UNRANK_SECONDS=%.3f CPP_WORD_MATCH=1\n'], ...
    numel(lengths), numel(actualWord), countSeconds, unrankSeconds);
fprintf(['STAGE55_POLYNOMIAL_MIDDLE_EXPERIMENTAL_PASS ', ...
    'PRODUCTION_ROUTE=UNCHANGED STAGE55=OPEN LAST_COMPLETED_STAGE=54\n']);
end

function enforceElapsed(timer, maximumSeconds, phase)
seconds = toc(timer);
if seconds > maximumSeconds
    error('Stage55:PolynomialMiddleBudget', ...
        'Phase %s exceeded its bounded time budget: %.3f s.', ...
        phase, seconds);
end
end

function writeExactText(path, content)
[fid, message] = fopen(path, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'Stage55:PolynomialMiddleWriteOpen', message);
guard = onCleanup(@() fclose(fid)); %#ok<NASGU>
written = fwrite(fid, content, 'char');
assert(written == numel(content), ...
    'Stage55:PolynomialMiddleWriteTruncated');
clear guard
end
