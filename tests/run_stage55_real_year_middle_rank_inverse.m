function run_stage55_real_year_middle_rank_inverse()
% Stage55 / Polski: opposite-direction exact-rank witness for the
% real 4244-day year-5000 MIDDLE rank's persisted three-day prefix.
% Separate joint first-letter DP; never calls adjoint unrank.
% No claim of full-word completion or independent normative oracle.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
guard=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>
L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
    97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
    97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
prefix=[1 2 3];
assert(numel(L)==45 && sum(L)==4244,'Stage55:FixtureChanged');
file=fullfile(root,'logs', ...
    'STAGE55_REAL_YEAR_INNER_CURSOR_AFTER_3.json');
assert(exist(file,'file')==2,'Stage55:ThirdDayCheckpointMissing');
checkpoint=jsondecode(fileread(file));
assert(isstruct(checkpoint) && isscalar(checkpoint) && ...
    strcmp(checkpoint.schema,'pastafari-weave-cursor-v1') && ...
    isequal(double(checkpoint.originalLengths(:).'),L) && ...
    ischar(checkpoint.rankDecimal) && ischar(checkpoint.countDecimal) && ...
    ~isempty(regexp(checkpoint.rankDecimal,'^[1-9][0-9]*$','once')) && ...
    ~isempty(regexp(checkpoint.countDecimal,'^[1-9][0-9]*$','once')) && ...
    checkpoint.stepsComputed==3 && checkpoint.openedUpTo==3 && ...
    checkpoint.closedUpTo==0 && ~checkpoint.done, ...
    'Stage55:CheckpointStructureMismatch');
expected=L;
expected(prefix)=expected(prefix)-1;
assert(isequal(double(checkpoint.remaining(:).'),expected) && ...
    sum(checkpoint.remaining)==4241, ...
    'Stage55:ThirdDayMultiplicityMismatch');
savedRank=pastafari.BigInt(checkpoint.rankDecimal);
savedCount=pastafari.BigInt(checkpoint.countDecimal);
one=pastafari.BigInt(1);
assert(savedRank>=one && savedRank<=savedCount && ...
    numel(checkpoint.countDecimal)==6765, ...
    'Stage55:ThirdDayRankRange');

timer=tic;
[low,high,ranked]=pastafari.rankGeneralWeavePrefix( ...
    L,L,0,0,prefix,'joint');
seconds=toc(timer);
mid=ranked.totalCount.floorDiv(pastafari.BigInt(2))+one;
assert(low<=mid && mid<=high && ...
    high-low+one==ranked.count && ...
    savedCount==ranked.count && ...
    savedRank==mid-low+one && ...
    ranked.stepsComputed==3 && ...
    ranked.openedUpTo==3 && ranked.closedUpTo==0 && ...
    isequal(ranked.remaining,expected) && ...
    ~ranked.done && numel(char(ranked.totalCount))==6765, ...
    'Stage55:MiddleRankInverseMismatch');
fprintf(['STAGE55_REAL_YEAR_MIDDLE_RANK_INVERSE_PASS ', ...
    'YEAR=5000 MONTHS=45 DAYS=4244 PREFIX=[1 2 3] ', ...
    'LEFT=4241 COUNT_DIGITS=%d SECONDS=%.3f\n'], ...
    numel(char(savedCount)),seconds);
fprintf(['STAGE55_REAL_YEAR_MIDDLE_RANK_INVERSE_SCOPE ', ...
    'THREE_DAYS_ONLY=1 NORMATIVE_ORACLE=NOT_RUN ', ...
    'FULL_WORD=NOT_RUN STAGE55=OPEN\n']);
end
