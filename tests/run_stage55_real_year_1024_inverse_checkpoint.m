function run_stage55_real_year_1024_inverse_checkpoint()
% Experimental, exact middle rank of 1024 CONSECUTIVE days from the
% genuine production-selected year 5000, AFTER all 45 months were opened.
% The initial 45 opening letters have already occurred in canonical
% order; this 4199-day suffix is NOT the complete 4244-day year.
%
% Primary checks:
%  1) exact 1024-day rank->letters->rank interval roundtrip;
%  2) independent 96-day rational versus common child-block DP;
%  3) portable exact BigInt JSON checkpoint at day 1024;
%  4) 32 additional letters identical across generic lazy and all-open
%     engines after verified JSON restore.
%
% No approximate counts, no production/main modifications, no Stage55
% final normative-oracle completion claim.
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
addpath(fullfile(root,'src'));
cleanup=onCleanup(@() rmpath(fullfile(root,'src'))); %#ok<NASGU>

L=[115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
   97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
   97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
K=numel(L);
R=L-1;
assert(K==45 && sum(L)==4244 && sum(R)==4199);
one=pastafari.BigInt(1);
total=pastafari.countWholeWeavingSuffixByEndpoints(R,K,0);
rank=total.floorDiv(pastafari.BigInt(2))+one;
assert(rank>one && rank<total && numel(char(total))==6745, ...
    'Chosen native checkpoint rank must be interior and exact.');

unrankTimer=tic;
[letters,after]=pastafari.unrankAllOpenedWeaveSuffixChunk( ...
    R,0,rank,1024,'common');
unrankSeconds=toc(unrankTimer);
assert(numel(letters)==1024 && after.stepsComputed==1024 && ...
    sum(after.remaining)==3175 && ~after.done && ...
    after.rank>=one && after.rank<=after.count, ...
    '1024-day exact interior-rank unrank lost its suffix invariant.');
fprintf(['STAGE_55_REAL_YEAR_1024_UNRANK_PASS MONTHS=45 ', ...
    'INITIAL_DAYS=4199 STEPS=1024 REMAINING=3175 ', ...
    'SECONDS=%.3f COUNT_DIGITS=%d\n'], ...
    unrankSeconds,numel(char(after.count)));

inverseTimer=tic;
[lo,hi,inverse]=pastafari.rankAllOpenedWeavePrefix( ...
    R,0,letters,'common');
inverseSeconds=toc(inverseTimer);
assert(rank>=lo && rank<=hi && ...
    rank-lo+one==after.rank && hi-lo+one==after.count && ...
    inverse.totalCount==total && ...
    isequal(inverse.remaining,after.remaining) && ...
    inverse.closedUpTo==after.closedUpTo && ...
    inverse.stepsComputed==1024 && ~inverse.done, ...
    'Exact 1024-day inverse rank interval contradicts unrank cursor.');
fprintf(['STAGE_55_REAL_YEAR_1024_INVERSE_PASS ', ...
    'STEPS=1024 SECONDS=%.3f RANK_DIGITS=%d\n'], ...
    inverseSeconds,numel(char(rank)));

% Independent rational child-block method (different formulas,
% multiplication/division strategy) checks the FIRST 96 steps,
% without repeating slow rational algebra for all 1024 positions.
referenceTimer=tic;
[rl,rh,rc]=pastafari.rankAllOpenedWeavePrefix( ...
    R,0,letters(1:96),'rational');
[cl,ch,cc]=pastafari.rankAllOpenedWeavePrefix( ...
    R,0,letters(1:96),'common');
referenceSeconds=toc(referenceTimer);
assert(rl==cl && rh==ch && rc.count==cc.count && ...
    rc.totalCount==total && ...
    isequal(rc.remaining,cc.remaining) && ...
    rc.closedUpTo==cc.closedUpTo, ...
    '96-day independent rational/common count differential failed.');
fprintf(['STAGE_55_REAL_YEAR_1024_INDEPENDENT_BLOCKS_PASS ', ...
    'STEPS=96 SECONDS=%.3f\n'],referenceSeconds);

% Preserve ALL digits in a portable checkpoint; the restoring code
% re-computes the exact 3175-day suffix count independently.
saved=struct('remaining',after.remaining, ...
    'openedUpTo',K,'closedUpTo',after.closedUpTo, ...
    'rank',after.rank,'count',after.count,'done',after.done, ...
    'stepsComputed',after.stepsComputed);
json=pastafari.serializeExactWeaveCursorJson(L,saved);
assert(contains(json,'"rankDecimal":"') && ...
    contains(json,'"countDecimal":"'), ...
    'BigInt JSON must use decimal STRINGS and never JSON numbers.');
[restoredL,restored]=pastafari.restoreExactWeaveCursorJson(json);
assert(isequal(restoredL,L) && ...
    isequal(restored.remaining,after.remaining) && ...
    restored.openedUpTo==K && ...
    restored.closedUpTo==after.closedUpTo && ...
    restored.rank==after.rank && restored.count==after.count && ...
    ~restored.done, ...
    'Full-scale checkpoint damaged a rank, count or frontier.');
[nextGeneral,gc]=pastafari.unrankGeneralWeaveSuffixChunkLazyJoint( ...
    restoredL,restored.remaining,restored.openedUpTo, ...
    restored.closedUpTo,restored.rank,32);
[nextOpen,oc]=pastafari.unrankAllOpenedWeaveSuffixChunk( ...
    after.remaining,after.closedUpTo,after.rank,32,'common');
assert(isequal(nextGeneral,nextOpen) && numel(nextGeneral)==32 && ...
    gc.rank==oc.rank && gc.count==oc.count && ...
    isequal(gc.remaining,oc.remaining) && ...
    gc.closedUpTo==oc.closedUpTo && ...
    sum(gc.remaining)==3143, ...
    'JSON resume diverged between independent all-open/generic engines.');
fprintf(['STAGE_55_REAL_YEAR_1024_CHECKPOINT_RESUME_PASS ', ...
    'STEPS=1024 RESUMED=32 REMAINING=3143\n']);
fprintf('STAGE_55_REAL_YEAR_1024_EXPERIMENTAL_PASS\n');
end
