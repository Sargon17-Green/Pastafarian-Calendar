function run_stage55_real_year_inner_cursor_probe()
% Stage 55: bounded diagnostic of a genuinely interior lexical rank for
% the REAL 45-month, 4244-day year-5000 fixture. Two chunks of two days,
% one persisted and independently re-counted JSON cursor in between.
% This is NOT the production stream-selected rank, full-word unrank,
% independent full normative oracle or Stage55 final acceptance.
% No exponential remaining-vector DAG is constructed here.
here = fileparts(mfilename('fullpath'));
root = fileparts(here);
addpath(fullfile(root, 'src'));
cleanup = onCleanup(@() rmpath(fullfile(root, 'src'))); %#ok<NASGU>

L = [115 108 119 109 106 81 115 114 117 120 98 52 81 97 121 ...
     97 115 96 107 61 106 115 119 39 84 103 115 107 55 119 ...
     97 50 122 110 81 54 101 83 88 40 25 77 98 122 105];
assert(numel(L) == 45 && sum(L) == 4244 && min(L) == 25, ...
    'Stage55:RealYearFixtureChanged');

one = pastafari.BigInt(1);
timer = tic;
total = pastafari.countWholeWeavingSuffixByFirstEndpoint(L, 0, 0);
rank = total.floorDiv(pastafari.BigInt(2)) + one;
assert(rank > one && rank < total && numel(char(total)) == 6765, ...
    'Stage55:InternalRankCount');
countSeconds = toc(timer);
fprintf(['STAGE55_INNER_COUNT MONTHS=45 DAYS=4244 ', ...
         'COUNT_DIGITS=%d SECONDS=%.3f\n'], ...
         numel(char(total)), countSeconds);
enforceElapsed(timer, 240, 'initial exact count');

% One four-day reference traversal, not a full 4244-day operation.
timer = tic;
[reference, expected] = pastafari.unrankGeneralWeaveSuffixChunkAdjoint( ...
    L, L, 0, 0, rank, 4);
referenceSeconds = toc(timer);
assert(numel(reference) == 4 && expected.stepsComputed == 4 && ...
    expected.initialCount == total && ...
    sum(expected.remaining) == 4240 && ~expected.done, ...
    'Stage55:ReferencePrefix');
fprintf('STAGE55_INNER_REFERENCE STEPS=4 SECONDS=%.3f\n', ...
    referenceSeconds);
enforceElapsed(timer, 240, 'four-day reference');

timer = tic;
[first, cursor] = pastafari.unrankGeneralWeaveSuffixChunkAdjoint( ...
    L, L, 0, 0, rank, 2);
firstSeconds = toc(timer);
assert(numel(first) == 2 && first(1) == 1 && ...
    cursor.stepsComputed == 2 && sum(cursor.remaining) == 4242 && ...
    cursor.initialCount == total && ~cursor.done && ...
    cursor.rank >= one && cursor.rank <= cursor.count, ...
    'Stage55:FirstChunk');
fprintf('STAGE55_INNER_FIRST_CHUNK STEPS=2 SECONDS=%.3f\n', ...
    firstSeconds);
enforceElapsed(timer, 240, 'first chunk');

if exist(fullfile(root, 'logs'), 'dir') ~= 7
    mkdir(fullfile(root, 'logs'));
end
checkpointFile = fullfile(root, 'logs', ...
    'STAGE55_REAL_YEAR_INNER_CURSOR_AFTER_2.json');
text = pastafari.serializeExactWeaveCursorJson(L, cursor);
writeExactText(checkpointFile, text);
assert(strcmp(fileread(checkpointFile), text), ...
    'Stage55:CheckpointWrite');
data = jsondecode(text);
assert(ischar(data.rankDecimal) && ischar(data.countDecimal) && ...
    strcmp(data.rankDecimal, char(cursor.rank)) && ...
    strcmp(data.countDecimal, char(cursor.count)), ...
    'Stage55:CheckpointBigInt');

timer = tic;
[restoredL, restored] = pastafari.restoreExactWeaveCursorJson( ...
    fileread(checkpointFile));
restoreSeconds = toc(timer);
assert(isequal(restoredL, L) && ...
    isequal(restored.remaining, cursor.remaining) && ...
    restored.openedUpTo == cursor.openedUpTo && ...
    restored.closedUpTo == cursor.closedUpTo && ...
    restored.rank == cursor.rank && restored.count == cursor.count && ...
    restored.stepsComputed == cursor.stepsComputed, ...
    'Stage55:CheckpointRestore');
fprintf(['STAGE55_INNER_CHECKPOINT_RESTORED ', ...
         'COUNT_DIGITS=%d SECONDS=%.3f\n'], ...
    numel(data.countDecimal), restoreSeconds);
enforceElapsed(timer, 240, 'exact checkpoint recount');

timer = tic;
[second, after] = pastafari.unrankGeneralWeaveSuffixChunkAdjoint( ...
    restoredL, restored.remaining, restored.openedUpTo, ...
    restored.closedUpTo, restored.rank, 2);
secondSeconds = toc(timer);
assembled = [first, second];
assert(isequal(assembled, reference) && ...
    numel(second) == 2 && after.stepsComputed == 2 && ...
    isequal(after.remaining, expected.remaining) && ...
    after.openedUpTo == expected.openedUpTo && ...
    after.closedUpTo == expected.closedUpTo && ...
    after.rank == expected.rank && after.count == expected.count && ...
    sum(after.remaining) == 4240 && ...
    after.rank >= one && after.rank <= after.count && ~after.done, ...
    'Stage55:ChunkReferenceMismatch');

% Independent arithmetic check of the remaining multiplicities.
replayed = L;
for i = 1:numel(assembled)
    letter = assembled(i);
    assert(letter >= 1 && letter <= numel(L), ...
        'Stage55:InvalidPrefixLetter');
    replayed(letter) = replayed(letter) - 1;
end
assert(isequal(replayed, after.remaining), ...
    'Stage55:PrefixMultiplicityMismatch');
fprintf(['STAGE55_INNER_SECOND_CHUNK STEPS=2 SECONDS=%.3f ', ...
         'TOTAL_PREFIX=4 REMAINING=4240\n'], secondSeconds);
enforceElapsed(timer, 240, 'resumed chunk');
emitPeakResidentMemory();
fprintf(['STAGE55_REAL_YEAR_INNER_CURSOR_PROBE_PASS ', ...
    'PREFIX_ONLY=4 TOTAL_DAYS=4244 ', ...
    'NO_FULL_WORD_OR_NORMATIVE_ORACLE_CLAIM\n']);
end

function enforceElapsed(timer, maximumSeconds, phase)
seconds = toc(timer);
if seconds > maximumSeconds
    error('Stage55:DiagnosticBudget', ...
        'Phase %s exceeded diagnostic wall-time budget: %.3f s.', ...
        phase, seconds);
end
end

function writeExactText(path, content)
[fid, message] = fopen(path, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'Stage55:CheckpointOpen', message);
guard = onCleanup(@() fclose(fid)); %#ok<NASGU>
written = fwrite(fid, content, 'char');
assert(written == numel(content), 'Stage55:CheckpointTruncated');
end

function emitPeakResidentMemory()
% Linux runner measurement only; do not mistake MATLAB heap estimates
% or a shell child's RSS for the MATLAB process's actual high-water mark.
try
    if isunix
        pid = feature('getpid');
        status = fileread(sprintf('/proc/%d/status', pid));
        value = regexp(status, 'VmHWM:\\s+(\\d+)\\s+kB', ...
            'tokens', 'once');
        if ~isempty(value)
            fprintf('STAGE55_MATLAB_PROCESS_PEAK_RSS_KIB=%s\n', ...
                value{1});
            return
        end
    end
catch
    % Not every MATLAB runtime exposes feature('getpid').
end
fprintf('STAGE55_MATLAB_PROCESS_PEAK_RSS_UNAVAILABLE\n');
end
