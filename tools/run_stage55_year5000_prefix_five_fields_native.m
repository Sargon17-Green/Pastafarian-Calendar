function run_stage55_year5000_prefix_five_fields_native()
% Bounded year-5000 first five fields; NOT full finalMonsterIntegration.
root=fileparts(fileparts(mfilename('fullpath')));
src=fullfile(root,'src'); addpath(src);
cleanupPath=onCleanup(@() rmpath(src)); %#ok<NASGU>
logs=fullfile(root,'logs');
if exist(logs,'dir')~=7, mkdir(logs); end
diary(fullfile(logs,'STAGE55_YEAR5000_PREFIX_FIVE_FIELDS_NATIVE.log'));
diaryGuard=onCleanup(@() diary('off')); %#ok<NASGU>
f=jsondecode(fileread(fullfile(root,'tests','fixtures', ...
    'stage55_year5000_appendix_a_metadata.json')));
c=jsondecode(fileread(fullfile(logs, ...
    'STAGE55_REAL_YEAR_INNER_CURSOR_AFTER_5.json')));
L=double(f.month_lengths(:).');
C=double(f.cutlet_day_lengths(:).');
remaining=double(c.remaining(:).');
nameIds=double(f.month_name_indices(:).');
assert(f.year==5000 && f.calculation_day==-15055671 && ...
    f.first_day==-15057702 && f.last_day==-15053459 && ...
    numel(L)==45 && sum(L)==4244 && numel(C)==6 && ...
    C(1)==759 && sum(C)==4244 && ...
    strcmp(c.schema,'pastafari-weave-cursor-v1'), ...
    'Stage55:PrefixMetadataMismatch');
assert(c.stepsComputed==5 && c.openedUpTo==5 && ...
    c.closedUpTo==0 && ~c.done && ...
    isequal(double(c.originalLengths(:).'),L) && ...
    isequal(remaining(1:5),L(1:5)-1) && ...
    isequal(remaining(6:end),L(6:end)) && ...
    sum(remaining)==4239,'Stage55:PrefixCursorMismatch');
assert(isequal(nameIds(1:5),[18 14 37 28 24]) && ...
    f.cutlet_name_indices(1)==15, ...
    'Stage55:PrefixNameFixtureMismatch');
names={'wielbłąd','żebro','burza','Niniwa','śledziona'};
catalog=pastafari.sourceLanguageCatalog();
assert(strcmp(catalog.cutlets(15).text,'Akad'), ...
    'Stage55:PrefixCutletCatalogMismatch');
open=pastafari.BigInt(f.first_day-1);
weave=1:5;
for pos=1:5
    day=pastafari.BigInt(f.first_day+pos-1);
    ctx=pastafari.MonsterContext(pastafari.BigInt(f.calculation_day),day);
    [ctx,monthId,monthDay]=pastafari.MonthDayCompatibilityRoute.call( ...
        ctx,weave,open,day);
    fiveFields={pastafari.BigInt(f.year),'Akad',pastafari.BigInt(pos), ...
        catalog.months(nameIds(pos)).text,monthDay};
    assert(monthId==pos && numel(fiveFields)==5 && ...
        fiveFields{1}==pastafari.BigInt(5000) && ...
        strcmp(fiveFields{2},'Akad') && ...
        fiveFields{3}==pastafari.BigInt(pos) && ...
        strcmp(fiveFields{4},names{pos}) && ...
        fiveFields{5}==pastafari.BigInt(1) && ...
        any(strcmp(ctx.branchTrace,'DISCOVERY_25_CONTIGUOUS_MONTH_DAY')) && ...
        any(strcmp(ctx.branchTrace,'PATCH_25_OCCURRENCE_COUNT')), ...
        'Stage55:PrefixFiveFieldsMismatch');
    fprintf(['STAGE55_PREFIX_ROW POSITION=%d YEAR=5000 ', ...
        'CUTLET_INDEX=15 CUTLET_DAY=%d MONTH_INDEX=%d MONTH_DAY=1\n'], ...
        pos,pos,nameIds(pos));
end
for pos=[0 6]
    day=pastafari.BigInt(f.first_day+pos-1);
    ctx=pastafari.MonsterContext(pastafari.BigInt(f.calculation_day),day);
    rejected=false;
    try
        pastafari.MonthDayCompatibilityRoute.call(ctx,weave,open,day);
    catch err
        rejected=strcmp(err.identifier,'Pastafari:MonthDay:TargetOutsideYear');
    end
    assert(rejected,'Stage55:PrefixOutsideNotRejected');
end
fprintf('STAGE55_YEAR5000_PREFIX_FIVE_FIELDS_NATIVE_PASS CASES=5 FIELDS=5 REJECTED=2\n');
fprintf('STAGE55_FULL_YEAR_CANONICAL_ORACLE_NOT_VERIFIED\n');
fprintf('STAGE55_CROSS_ENGINE_SOAK_NOT_VERIFIED\n');
fprintf('STAGE55_FINAL_STAGE_PASS_NOT_VERIFIED\n');
end
