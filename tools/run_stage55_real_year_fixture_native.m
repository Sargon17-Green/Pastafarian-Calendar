function run_stage55_real_year_fixture_native()
% Stage55 real-year BOUNDED projection, not finalMonsterIntegration.
% Metadata from audited fixture is NOT an independent canonical oracle.
root=fileparts(fileparts(mfilename('fullpath')));
src=fullfile(root,'src');
addpath(src);
pathGuard=onCleanup(@() rmpath(src)); %#ok<NASGU>
logs=fullfile(root,'logs');
if exist(logs,'dir')~=7, mkdir(logs); end
diary(fullfile(logs,'STAGE55_REAL_YEAR_FIXTURE_NATIVE.log'));
diaryGuard=onCleanup(@() diary('off')); %#ok<NASGU>
f=jsondecode(fileread(fullfile(root,'tests','fixtures', ...
    'stage55_year5000_appendix_a_metadata.json')));
L=double(f.month_lengths(:).');
C=double(f.cutlet_day_lengths(:).');
cn=double(f.cutlet_name_indices(:).');
mn=double(f.month_name_indices(:).');
assert(f.year==5000 && f.calculation_day==-15055671 && ...
    f.first_day==-15057702 && f.last_day==-15053459 && ...
    f.months==45 && numel(L)==45 && sum(L)==4244 && ...
    all(L>=3) && f.last_day-f.first_day+1==4244, ...
    'Stage55:YearFixtureInvalid');
assert(f.cutlet_count==6 && numel(C)==6 && sum(C)==4244 && ...
    all(C>0) && numel(cn)==6 && numel(unique(cn))==6 && ...
    numel(mn)==45 && numel(unique(mn))==45 && ...
    f.cutlet_required_boundary==4 && ...
    isequal(double(f.cutlet_gate_partition(:).'),[1 2 1 2 1 1]) && ...
    f.open_gate_index==-4 && f.close_gate_index==4 && ...
    f.evidence.five_field_cases==48 && ...
    f.evidence.boundary_offsets==12, ...
    'Stage55:CutletFixtureInvalid');
assert(contains(f.contract,'NOT native differential proof') && ...
    any(contains(string(f.not_verified),'native MATLAB comparison')), ...
    'Stage55:FixtureScopeInvalid');
catalog=pastafari.sourceLanguageCatalog();
assert(all(cn>=1 & cn<=numel(catalog.cutlets)) && ...
    all(mn>=1 & mn<=numel(catalog.months)), ...
    'Stage55:NameIndexInvalid');

% Independently constructed closed-form edge words, not production unrank.
k=numel(L);
low=repelem(1:k,L);
middle=[];
for j=k:-1:1
    middle=[middle,repmat(j,1,L(j)-2)]; %#ok<AGROW>
end
high=[1:k,middle,1:k];
low2=low;
p=sum(L(1:end-1));
assert(low(p)==k-1 && low(p+1)==k,'Stage55:LowEdgeInvalid');
low2([p,p+1])=low2([p+1,p]);
high2=high;
q=find(high(1:end-1)==2 & high(2:end)==1,1,'last');
assert(~isempty(q),'Stage55:HighEdgeInvalid');
high2([q,q+1])=high2([q+1,q]);
words={low,low2,high2,high};
moments=[264303486 8847605690;264303485 8847605601; ...
    131812553 2927435647;131812552 2927435644];
ends=cumsum(C);
starts=[1,ends(1:end-1)+1];
positions=sort([starts,ends]);
assert(numel(unique(positions))==12 && positions(1)==1 && ...
    positions(end)==4244,'Stage55:BoundaryPositionsInvalid');
origin=pastafari.BigInt(f.first_day-1);
calc=pastafari.BigInt(f.calculation_day);
cases=0;
differences=0;
for edge=1:4
    w=words{edge};
    assert(numel(w)==4244 && ...
        isequal(accumarray(w(:),1,[k 1]),L(:)), ...
        'Stage55:WordMultiplicityInvalid');
    first=zeros(1,k);
    last=zeros(1,k);
    for j=1:k
        occurrences=find(w==j);
        first(j)=occurrences(1);
        last(j)=occurrences(end);
    end
    assert(all(diff(first)>0) && all(diff(last)>0), ...
        'Stage55:WordLegalityInvalid');
    idx=1:4244;
    assert(isequal([sum(idx.*w),sum(idx.*w.^2)], ...
        moments(edge,:)),'Stage55:EdgeMomentsInvalid');
    for pos=positions
        day=pastafari.BigInt(f.first_day+pos-1);
        ctx=pastafari.MonsterContext(calc,day);
        [ctx,actualMonth,actualDay]= ...
            pastafari.MonthDayCompatibilityRoute.call(ctx,w,origin,day);
        wantedMonth=w(pos);
        wantedDay=sum(w(1:pos)==wantedMonth);
        part=find(pos<=ends,1,'first');
        cutletDay=pos-starts(part)+1;
        cutletText=catalog.cutlets(cn(part)).text;
        monthText=catalog.months(mn(wantedMonth)).text;
        projected={pastafari.BigInt(f.year),cutletText, ...
            pastafari.BigInt(cutletDay),monthText,actualDay};
        assert(numel(projected)==5 && ...
            projected{1}==pastafari.BigInt(5000) && ...
            strcmp(projected{2},cutletText) && ...
            projected{3}==pastafari.BigInt(cutletDay) && ...
            strcmp(projected{4},monthText) && ...
            projected{5}==pastafari.BigInt(wantedDay) && ...
            actualMonth==wantedMonth, ...
            'Stage55:PATCH25ProjectionMismatch');
        assert(any(strcmp(ctx.branchTrace, ...
            'DISCOVERY_25_CONTIGUOUS_MONTH_DAY')) && ...
            any(strcmp(ctx.branchTrace,'PATCH_25_OCCURRENCE_COUNT')), ...
            'Stage55:ProductionRouteNotExecuted');
        if ctx.legacyContiguousDayInMonth~=actualDay
            differences=differences+1;
        end
        cases=cases+1;
    end
end
assert(cases==48 && differences>0,'Stage55:InsufficientCoverage');
fprintf(['STAGE55_REAL_YEAR_FIXTURE_NATIVE_PASS ', ...
    'YEAR=5000 MONTHS=45 DAYS=4244 CUTLETS=6 ', ...
    'EDGE_WORDS=4 BOUNDARY_OFFSETS=12 CASES=%d ', ...
    'FIELDS=5 PATCH25_CORRECTIONS=%d\n'],cases,differences);
fprintf('STAGE55_CUTLET_AND_NAME_FIELDS_PROJECTED_FROM_FIXTURE_ONLY\n');
fprintf('STAGE55_FULL_YEAR_CANONICAL_ORACLE_NOT_VERIFIED\n');
fprintf('STAGE55_MIDDLE_RANK_AND_SOAK_NOT_VERIFIED\n');
fprintf('STAGE55_FINAL_STAGE_PASS_NOT_VERIFIED\n');
end
