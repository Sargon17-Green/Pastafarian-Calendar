#!/usr/bin/env python3
"""Independent finite-scope QA12 receipt auditor; does not implement calendar math.

Consumes exactly four JSON receipts generated by Native PyFunge runners. Validates
pinned files, complete ordered-pair coverage, 16 lexical rejections, and swap
relations. Does NOT claim Stage-1 completion nor independently replay Native.
"""
from __future__ import annotations
import argparse
import copy
import json
from pathlib import Path
import sys

SOURCE='src/interleaved_work_counts.b98'
REF_COUNTS='reference/work_counts.b98'
REF_SAVE='reference/save.b98'
PINS={SOURCE:'560d6aa5807a7f766213a33835cce85eab0fa40c',
      REF_COUNTS:'f941efc793c9eee4accf5d03873f8ed029b16725',
      REF_SAVE:'7b5e79aa6e2bfb636717cb018a3db6a13fb2bb44'}
M=(1<<127)-1
DAYS=[('zero',0,0),('one',0,1),('two',0,2),('minus_one',1,1),
 ('minus_two',1,2),('foundation_minus_2',1,15055673),
 ('foundation_minus_1',1,15055672),('foundation',1,15055671),
 ('foundation_plus_1',1,15055670),('foundation_plus_2',1,15055669),
 ('max_save',0,M),('over_save',0,M+1),
 ('negative_max_save',1,M),('negative_over_save',1,M+1),
 ('very_large',0,10**80+17),('very_negative',1,10**80+19)]
INVALID=[('bad_calc_sign_2','2 1 0 1'),('bad_target_sign_2','0 1 2 1'),
 ('negative_zero_calc','1 0 0 1'),('negative_zero_target','0 1 1 0'),
 ('explicit_negative_calc','-1 1 0 1'),('explicit_negative_target','0 1 -1 1'),
 ('plus_calc','+0 1 0 1'),('plus_target','0 1 +0 1'),
 ('garbage_calc','x 1 0 1'),('garbage_target','0 1 0 x'),
 ('missing_field','0 1 0'),('extra_field','0 1 0 1 5'),
 ('empty_line',''),('double_sign','--1 1 0 1'),
 ('sign_10','10 1 0 1'),('trailing_garbage','0 1 0 1 xyz')]


def require(ok,why):
    if not ok:raise AssertionError(why)


def validate(records):
    require(len(records)==4,'four independent Native shard receipts required')
    seen=set();got_neg=set();sha_seen=set()
    for doc in records:
        shard=doc.get('shard')
        require(isinstance(shard,int) and shard in range(4) and shard not in sha_seen,
                'duplicate/bad shard')
        sha_seen.add(shard)
        require(doc.get('complete') is True and doc.get('stage1_accepted') is False
                and doc.get('qa12_is_final_acceptance') is False,
                'receipt did not complete or claims unwarranted acceptance')
        require(doc.get('schema')=='bf98-stage1-qa12-native-boundary-grid-v1'
                and doc.get('source_blobs')==PINS and
                doc.get('universe_days')==16 and
                doc.get('all_unordered_pairs')==136 and
                doc.get('all_ordered_pairs')==256,
                'Native provenance/coverage pins drifted')
        expected=[(i,j) for i in range(16) for j in range(i,16)]
        expected=[p for k,p in enumerate(expected) if k%4==shard]
        actual=doc.get('cases')
        require(isinstance(actual,list) and len(actual)==len(expected),
                'shard lacks expected cases')
        for (i,j),case in zip(expected,actual):
            a,b=DAYS[i],DAYS[j]
            require(case.get('a')==a[0] and case.get('b')==b[0] and
                    case.get('canonical_input')=='%d %d %d %d'%(a[1],a[2],b[1],b[2])
                    and case.get('symmetric_check') is True,
                    'mislabelled or fabricated Native input '+repr((i,j)))
            x,y=case.get('normal_seven'),case.get('reversed_seven')
            require(isinstance(x,list) and isinstance(y,list) and
                    len(x)==len(y)==7 and all(isinstance(q,str)
                    and q.lstrip('-').isdigit() for q in x+y),
                    'invalid seven-output numeric format')
            require(x[0]==y[1] and x[1]==y[0] and x[2]==y[2]
                    and x[3]==y[3] and x[5]==y[6] and x[6]==y[5]
                    and int(x[4])+int(y[4])==4,
                    'Native swap invariants contradicted by receipt')
            if i==j:
                require(x==y and x[2]=='1' and x[4]=='2',
                        'equal-day invariant contradicted')
            require((i,j) not in seen,'duplicate native unordered pair')
            seen.add((i,j))
        neg=doc.get('negative_cases')
        expected_bad=INVALID[shard::4]
        require(isinstance(neg,list) and len(neg)==len(expected_bad),
                'missing negative lexical cases')
        for e,row in zip(expected_bad,neg):
            require(row.get('label')==e[0] and row.get('input')==e[1] and
                    row.get('output')==['-1']*7,
                    'invalid lexical rejection receipt')
            require(e[0] not in got_neg,'duplicated negative case')
            got_neg.add(e[0])
    require(len(seen)==136 and len(got_neg)==16 and len(sha_seen)==4,
            'incomplete coverage matrix')
    return {'shards':4,'unordered_pairs':136,'ordered_pairs':256,
            'negative_inputs':16,'source_pins':PINS,
            'scope':'finite-native-functional-regression-not-stage1-completion'}


def selftest():
    fake=[]
    allpairs=[(i,j) for i in range(16) for j in range(i,16)]
    for shard in range(4):
        document={'schema':'bf98-stage1-qa12-native-boundary-grid-v1',
          'shard':shard,'source_blobs':PINS,'universe_days':16,
          'all_unordered_pairs':136,'all_ordered_pairs':256,
          'complete':True,'stage1_accepted':False,
          'qa12_is_final_acceptance':False,'cases':[],'negative_cases':[]}
        for i,j in [p for k,p in enumerate(allpairs) if k%4==shard]:
            a,b=DAYS[i],DAYS[j]
            x=['1','3','2','4','3','3','5']
            y=['3','1','2','4','1','5','3']
            if i==j:
                x=y=['1','1','1','2','2','2','2']
            document['cases'].append({'a':a[0],'b':b[0],
              'canonical_input':'%d %d %d %d'%(a[1],a[2],b[1],b[2]),
              'symmetric_check':True,'normal_seven':x,'reversed_seven':y})
        document['negative_cases']=[{'label':a,'input':b,'output':['-1']*7}
                                    for a,b in INVALID[shard::4]]
        fake.append(document)
    require(validate(fake)['ordered_pairs']==256,'valid synthetic selftest refused')
    for label,mutate in (
        ('source_pin',lambda t:t[0]['source_blobs'].__setitem__(SOURCE,'0'*40)),
        ('duplicated_shard',lambda t:t[1].__setitem__('shard',0)),
        ('deleted_case',lambda t:t[0]['cases'].pop()),
        ('forged_numeric',lambda t:t[2]['cases'][0]['normal_seven'].__setitem__(2,'9')),
        ('invalid_accepted',lambda t:t[3]['negative_cases'][0].__setitem__('output',['1'])),
        ('false_acceptance',lambda t:t[0].__setitem__('stage1_accepted',True)),
    ):
        cloned=copy.deepcopy(fake)
        mutate(cloned)
        try:validate(cloned)
        except AssertionError:continue
        raise AssertionError('forged native receipt passed '+label)
    print('QA12_RECEIPT_AUDITOR_SELFTEST_PASS; 6/6 forged inputs rejected')


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('receipts',nargs='*')
    parser.add_argument('--selftest',action='store_true')
    args=parser.parse_args()
    selftest()
    if args.selftest:return
    require(len(args.receipts)==4,'exactly four independent Native JSON receipts')
    docs=[json.loads(Path(x).read_text(encoding='utf-8')) for x in args.receipts]
    summary=validate(docs)
    print('QA12_NATIVE_FINITE_BOUNDARY_GRID_RECEIPTS_PASS',json.dumps(summary,sort_keys=True))

if __name__=='__main__':main()
